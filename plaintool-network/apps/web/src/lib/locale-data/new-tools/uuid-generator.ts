export type UuidGeneratorLocaleSeed = {
  page: UuidPageSeed;
  feature: Omit<UuidGeneratorCopy, "ariaLabel" | "outdated">;
};

type LocalizedSeed = {
  page: Omit<UuidPageSeed, "faqs">;
  faqVersion: [string, string];
  faqRepeat: [string, string];
  faqSecret: [string, string];
  labels: {
    version: string;
    versions: [string, string, string, string, string, string];
    hints: [string, string, string, string, string, string];
    name: string;
    namePlaceholder: string;
    namespace: string;
    customNamespace: string;
    customNamespacePlaceholder: string;
    custom: string;
    quantity: string;
    quantityHint: string;
    format: string;
    formats: [string, string, string, string];
    letterCase: string;
    lower: string;
    upper: string;
    generate: string;
    results: string;
    empty: string;
    count: string;
    copyOne: string;
    copyAll: string;
    generated: string;
    copiedOne: string;
    copiedAll: string;
    downloaded: string;
    errors: [string, string, string, string, string];
  };
};

function createSeed(seed: LocalizedSeed): UuidGeneratorLocaleSeed {
  const [v4, v7, v1, v3, v5, v6] = seed.labels.versions;
  const [h4, h7, h1, h3, h5, h6] = seed.labels.hints;
  const [canonical, braces, urn, compact] = seed.labels.formats;
  const errors = seed.labels.errors;
  return {
    page: {
      ...seed.page,
      faqs: [
        { q: seed.faqVersion[0], a: seed.faqVersion[1] },
        { q: seed.faqRepeat[0], a: seed.faqRepeat[1] },
        { q: seed.faqSecret[0], a: seed.faqSecret[1] },
      ],
    },
    feature: {
      versionLabel: seed.labels.version,
      versionNames: { v4, v7, v1, v3, v5, v6 },
      versionHints: { v4: h4, v7: h7, v1: h1, v3: h3, v5: h5, v6: h6 },
      nameLabel: seed.labels.name,
      namePlaceholder: seed.labels.namePlaceholder,
      namespaceLabel: seed.labels.namespace,
      namespaceNames: {
        dns: "DNS",
        url: "URL",
        oid: "OID",
        x500: "X.500",
        custom: seed.labels.custom,
      },
      customNamespaceLabel: seed.labels.customNamespace,
      customNamespacePlaceholder: seed.labels.customNamespacePlaceholder,
      quantityLabel: seed.labels.quantity,
      quantityHint: seed.labels.quantityHint,
      formatLabel: seed.labels.format,
      formatNames: { canonical, braces, urn, compact },
      letterCaseLabel: seed.labels.letterCase,
      letterCaseNames: {
        lower: seed.labels.lower,
        upper: seed.labels.upper,
      },
      generate: seed.labels.generate,
      resultTitle: seed.labels.results,
      resultEmpty: seed.labels.empty,
      resultCount: seed.labels.count,
      copyOne: seed.labels.copyOne,
      copyAll: seed.labels.copyAll,
      generated: seed.labels.generated,
      copiedOne: seed.labels.copiedOne,
      copiedAll: seed.labels.copiedAll,
      downloaded: seed.labels.downloaded,
      errors: {
        "invalid-count": errors[0],
        "name-required": errors[1],
        "namespace-required": errors[2],
        "invalid-namespace": errors[3],
        "generation-failed": errors[4],
      },
    },
  };
}


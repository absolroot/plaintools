type BmiTranslation = {
  page: readonly [
    description: string,
    mobileDescription: string,
    guide: string,
    ...terms: readonly [string, string, string, string],
  ];
  feature: readonly [
    unitSystemLabel: string,
    metricUnit: string,
    usUnit: string,
    weightKilograms: string,
    heightCentimeters: string,
    weightPounds: string,
    heightFeet: string,
    heightInches: string,
    calculate: string,
    resultTitle: string,
    categoryLabel: string,
    underweight: string,
    healthy: string,
    overweight: string,
    obesity: string,
    healthyWeightRange: string,
    calculated: string,
    limitationTitle: string,
    limitationBody: string,
  ];
  errors: readonly [string, string, string, string, string, string, string];
};

function localizedBmiPack(
  title: string,
  translation: BmiTranslation,
): { page: Page; feature: BmiCalculatorCopy } {
  const [description, mobileDescription, guide, ...terms] = translation.page;
  const [
    unitSystemLabel,
    metricUnit,
    usUnit,
    weightKilograms,
    heightCentimeters,
    weightPounds,
    heightFeet,
    heightInches,
    calculate,
    resultTitle,
    categoryLabel,
    underweight,
    healthy,
    overweight,
    obesity,
    healthyWeightRange,
    calculated,
    limitationTitle,
    limitationBody,
  ] = translation.feature;
  const [
    nonFiniteInput,
    weightNotPositive,
    heightNotPositive,
    weightOutOfRange,
    heightOutOfRange,
    feetNotInteger,
    inchesOutOfRange,
  ] = translation.errors;
  return {
    page: { title, description, mobileDescription, guide, terms },
    feature: {
      ariaLabel: title,
      unitSystemLabel,
      metricUnit,
      usUnit,
      weightKilograms,
      heightCentimeters,
      weightPounds,
      heightFeet,
      heightInches,
      calculate,
      resultTitle,
      bmiLabel: "BMI",
      categoryLabel,
      categories: { underweight, healthy, overweight, obesity },
      healthyWeightRange,
      healthyWeightRangeTemplate: "{minimum}–{maximum} {unit}",
      kilogramUnit: "kg",
      poundUnit: "lb",
      calculated,
      limitationTitle,
      limitationBody,
      errors: {
        "non-finite-input": nonFiniteInput,
        "weight-not-positive": weightNotPositive,
        "height-not-positive": heightNotPositive,
        "weight-out-of-range": weightOutOfRange,
        "height-out-of-range": heightOutOfRange,
        "feet-not-integer": feetNotInteger,
        "inches-out-of-range": inchesOutOfRange,
      },
    },
  };
}


export function formatterSubnetFor(locale: Locale): FormatterSubnetLocaleSeed {
  const primary = {
    en,
    ko,
    es,
    de,
    ja,
    fr,
    "pt-BR": ptBR,
    it,
    nl,
    sv,
    ar,
    "zh-TW": zhTW,
  } as const;
  return locale in primary
    ? primary[locale as keyof typeof primary]
    : secondaryFormatterSubnetSeeds[
        locale as keyof typeof secondaryFormatterSubnetSeeds
      ];
}

